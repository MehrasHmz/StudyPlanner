const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const base = process.env.STUDYPLANNER_UI_URL || 'http://127.0.0.1:5815';
const output = process.env.STUDYPLANNER_UI_OUTPUT || '/private/tmp/studyplanner-phase5-visuals';
const sizes = [[1440, 900], [1024, 768], [768, 1024], [390, 844], [360, 800]];
fs.mkdirSync(output, { recursive: true });
let activeBrowser;

(async () => {
    const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--disable-gpu'] });
    activeBrowser = browser;
    const context = await browser.newContext();
    const page = await context.newPage();
    const failures = [], results = [], mutations = [];
    let controlledClock = false;
    page.on('pageerror', error => failures.push(error.message));
    page.on('request', request => { if (request.method() === 'POST') mutations.push(request.url()); });
    page.on('dialog', dialog => dialog.accept());
    const check = (name, value) => { assert.ok(value, name); results.push(name); };
    async function visit(route) {
        const response = await page.goto(base + route);
        assert.equal(response.status(), 200, route);
        await page.waitForLoadState('networkidle');
    }
    async function capture(name) {
        check(`${name}: POST forms contain CSRF tokens`, await page.locator('form[method="post"]').evaluateAll(forms => forms.every(form => form.querySelector('input[name="__RequestVerificationToken"]')?.value)));
        check(`${name}: visible controls have names`, await page.locator('button:visible, input:visible, select:visible, textarea:visible').evaluateAll(controls => controls.every(control => control.getAttribute('aria-label') || control.textContent.trim() || control.labels?.length || control.type === 'hidden')));
        for (const [width, height] of sizes) {
            await page.setViewportSize({ width, height });
            for (const theme of ['dark', 'light']) {
                await page.evaluate(theme => {
                    document.documentElement.dataset.theme = theme;
                    document.documentElement.dataset.bsTheme = theme;
                    localStorage.setItem('studyplanner-theme', theme);
                }, theme);
                if (controlledClock) await page.clock.runFor(50);
                else await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
                await page.screenshot({ path: path.join(output, `${name}-${width}-${theme}.png`), fullPage: true, animations: 'disabled' });
                check(`${name} ${width} ${theme}: no page overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
                check(`${name} ${width} ${theme}: visible images loaded`, await page.locator('img:visible').evaluateAll(images => images.every(img => img.complete && img.naturalWidth > 0)));
            }
        }
        await page.setViewportSize({ width: 1440, height: 900 });
    }
    await visit('/'); await capture('landing');
    await page.keyboard.press('Tab');
    check('keyboard skip link is reachable', await page.evaluate(() => document.activeElement.classList.contains('skip-link')));
    await page.locator('#themeToggle').click();
    const selectedTheme = await page.locator('html').getAttribute('data-theme');
    await page.reload();
    check('theme toggle persists across refresh', await page.locator('html').getAttribute('data-theme') === selectedTheme);
    await visit('/Auth/Register'); await capture('register');
    const email = `phase5-browser-${Date.now()}@example.test`, password = 'Browser-test-9!';
    await page.locator('#registerName').fill('Phase Five Browser');
    await page.locator('#registerEmail').fill(email);
    await page.locator('#registerPassword').fill(password);
    check('registration includes CSRF token', await page.locator('input[name="__RequestVerificationToken"]').count() > 0);
    await page.getByRole('button', { name: 'Create account' }).click();
    await page.waitForURL('**/Auth/Login'); await capture('login');
    await page.locator('[name="Email"]').fill(email);
    await page.locator('[name="Password"]').fill(password);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await page.waitForURL(base + '/'); await capture('dashboard-empty');
    await visit('/Categories/Create'); await capture('category-create');
    const category = `Browser category ${Date.now()}`;
    await page.locator('#Name').fill(category);
    await page.locator('#Description').fill('Isolated browser verification category');
    await page.locator('main form button[type="submit"]').click();
    await page.waitForURL('**/Categories'); await capture('categories');
    const categoryCard = page.locator('.card').filter({ hasText: category });
    const categoryEdit = await categoryCard.locator('a[href*="Edit"]').getAttribute('href');
    await visit(categoryEdit); await capture('category-edit');
    check('category edit retains id', Boolean(await page.locator('main input[name="Id"]').inputValue()));
    await page.locator('#Description').fill('Edited in real Chrome');
    await page.locator('main form button[type="submit"]').click();
    await page.waitForURL('**/Categories');
    await visit('/StudyItems/Create'); await capture('item-create');
    check('item default priority', await page.locator('#Priority').inputValue() === '3');
    check('item default duration', await page.locator('#EstimatedDurationMinutes').inputValue() === '30');
    await page.locator('#Title').fill('Browser verified study task');
    await page.locator('#Description').fill('UI workflow verification');
    await page.locator('#CategoryId').selectOption({ label: category });
    await page.locator('main form button[type="submit"]').click();
    await page.waitForURL('**/StudyItems'); await capture('items');
    const row = page.locator('tr').filter({ hasText: 'Browser verified study task' });
    const edit = await row.locator('a[href*="Edit"]').getAttribute('href');
    const focus = await row.locator('a[href*="Focus"]').getAttribute('href');
    await visit(edit); await capture('item-edit');
    check('item edit retains id', Boolean(await page.locator('main input[name="Id"]').inputValue()));
    await page.locator('#Title').fill('Browser edited study task');
    await page.locator('main form button[type="submit"]').click();
    await page.waitForURL('**/StudyItems');
    await visit('/'); await capture('dashboard');
    await page.setViewportSize({ width: 360, height: 800 });
    await page.getByRole('button', { name: 'Toggle navigation' }).click();
    check('mobile navigation expands', await page.locator('#nav').isVisible());
    await page.screenshot({ path: path.join(output, 'navigation-360.png'), fullPage: true });
    await visit('/Sessions'); await capture('session-planner');
    await page.getByRole('button', { name: 'Plan session' }).click();
    await page.waitForURL('**/Sessions/Plan'); await capture('session-plan');
    check('session has editable actual minutes', await page.locator('#minutes-0').count() === 1);
    await page.locator('#minutes-0').fill('17');
    await page.getByRole('button', { name: 'Complete session' }).click();
    await page.locator('#confirmAction').click();
    await page.waitForURL('**/Sessions');
    check('session completion succeeds with optional blank notes', await page.getByRole('status').filter({ hasText: /complet/i }).count() > 0);
    await visit(focus); await capture('focus');
    check('owned item entry title', await page.locator('#activeTask').textContent() === 'Browser edited study task');
    const beforeFocus = mutations.length;
    await page.locator('#editTaskButton').click();
    await page.locator('#taskTitle').fill('<img src=x onerror="window.focusXss=1">');
    await page.getByRole('button', { name: 'Save task' }).click();
    check('custom title is plain text', await page.locator('#activeTask img').count() === 0);
    await page.reload();
    check('custom item title survives refresh', (await page.locator('#activeTask').textContent()).startsWith('<img'));
    await page.clock.install();
    await page.reload();
    await page.clock.pauseAt(await page.evaluate(() => new Date(Date.now() + 1000).toISOString()));
    controlledClock = true;
    await page.locator('#customMinutes').fill('1');
    await page.locator('#customMinutes').blur();
    await page.locator('#startPauseButton').click();
    await page.clock.runFor(5000);
    check('countdown counts timestamp time', await page.locator('#timerDisplay').textContent() === '00:00:55');
    await page.locator('#startPauseButton').click();
    await page.clock.runFor(10000);
    check('pause freezes countdown', await page.locator('#timerDisplay').textContent() === '00:00:55');
    await page.reload();
    check('paused countdown restores', await page.locator('#focusExperience').getAttribute('data-timer-status') === 'paused' && await page.locator('#timerDisplay').textContent() === '00:00:55');
    await page.locator('#startPauseButton').click();
    await page.clock.fastForward(70000);
    check('delayed callbacks finish countdown', await page.locator('#focusExperience').getAttribute('data-timer-status') === 'completed');
    check('completion visible', await page.locator('#completionMessage').isVisible());
    await page.reload();
    check('completed state restored', await page.locator('#focusExperience').getAttribute('data-timer-status') === 'completed');
    await page.locator('#startPauseButton').click();
    await visit('/');
    await page.clock.fastForward(70000);
    await visit(focus);
    check('countdown completes while Focus page is absent', await page.locator('#focusExperience').getAttribute('data-timer-status') === 'completed');
    await page.locator('[value="stopwatch"]').check();
    await page.locator('#startPauseButton').click();
    await page.clock.runFor(5000);
    check('stopwatch elapsed', await page.locator('#timerDisplay').textContent() === '00:00:05');
    await page.reload();
    check('running stopwatch restored', await page.locator('#focusExperience').getAttribute('data-timer-status') === 'running');
    await page.locator('#startPauseButton').click();
    await page.locator('#resetButton').click();
    check('reset zeroes stopwatch', await page.locator('#timerDisplay').textContent() === '00:00:00');
    await page.locator('#fullscreenButton').click();
    const realFullscreen = await page.evaluate(() => Boolean(document.fullscreenElement));
    check('fullscreen or fallback entered', realFullscreen || await page.locator('#focusExperience').getAttribute('data-immersive') === 'true');
    await page.locator('#fullscreenButton').click();
    check('fullscreen exits', await page.evaluate(() => !document.fullscreenElement));
    await page.evaluate(() => { document.getElementById('focusExperience').requestFullscreen = () => Promise.reject(new Error('Test denied')); });
    await page.locator('#fullscreenButton').click();
    check('denied fullscreen falls back', await page.locator('#focusExperience').getAttribute('data-immersive') === 'true');
    await page.keyboard.press('Escape');
    check('Escape exits fallback', await page.locator('#focusExperience').getAttribute('data-immersive') === 'false');
    check('fullscreen notice clears on exit', await page.locator('#focusNotice').textContent() === '');
    await page.locator('#editTaskButton').click();
    await page.keyboard.press('Escape');
    check('task dialog supports keyboard cancellation', await page.locator('#taskDialog').isHidden());
    check('one interval active', await page.evaluate(() => window.__focusController.activeIntervals === 1));
    await page.addScriptTag({ url: base + '/js/focus.js' });
    check('duplicate initialization guarded', await page.evaluate(() => window.__focusController.activeIntervals === 1));
    check('destroy cleans interval', await page.evaluate(() => { const controller = window.__focusController; controller.destroy(); return controller.activeIntervals === 0 && !window.__focusController; }));
    await page.addScriptTag({ url: base + '/js/focus.js' });
    check('clean reinitialization starts one interval', await page.evaluate(() => window.__focusController.activeIntervals === 1));
    await page.locator('#editTaskButton').click();
    await page.locator('#taskTitle').fill('W'.repeat(200));
    await page.getByRole('button', { name: 'Save task' }).click();
    await capture('focus-long-title');
    check('long task does not overlap timer', await page.evaluate(() => document.getElementById('activeTask').getBoundingClientRect().bottom < document.getElementById('timerDisplay').getBoundingClientRect().top));
    await page.locator('#showClock').uncheck();
    check('optional clock hidden', await page.locator('#localClock').isHidden());
    check('focus sends no mutation requests', mutations.length === beforeFocus);
    check('no JavaScript errors', failures.length === 0);
    await visit('/');
    const key = await page.evaluate(() => 'studyplanner:focus:v1:' + document.body.dataset.userId);
    await page.locator('.nav-user').click();
    await page.getByRole('button', { name: 'Sign out' }).click();
    await page.waitForURL(base + '/');
    check('logout clears current user timer', await page.evaluate(key => localStorage.getItem(key) === null, key));
    await page.goto(base + '/Focus');
    check('logout protects Focus', page.url().includes('/Auth/Login'));
    const evidence = { base, date: new Date().toISOString(), browser: await browser.version(), results, failures, realFullscreen, screenshots: fs.readdirSync(output).filter(name => name.endsWith('.png')) };
    fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify(evidence, null, 2));
    console.log(JSON.stringify({ checks: results.length, screenshots: evidence.screenshots.length, failures, realFullscreen, output }));
    await browser.close();
})().catch(async error => { console.error(error); await activeBrowser?.close(); process.exitCode = 1; });
